import type { SupabaseClient, QueryData } from "@supabase/supabase-js";
import type { Database, Tables } from "../../lib/supabase/database.types";
import type { createClient as createBrowserClient } from "../../lib/supabase/client";
import type { createClient as createServerClient } from "../../lib/supabase/server";

// Compile-only checks: this function is never executed and never contacts Supabase.
// A failing @ts-expect-error means an unsafe operation has become accepted.
export function databaseContract(
  client: SupabaseClient<Database>,
  browser: ReturnType<typeof createBrowserClient>,
  server: Awaited<ReturnType<typeof createServerClient>>,
) {
  // @ts-expect-error Unknown table names must not be accepted.
  client.from("missing_table");
  // @ts-expect-error Browser clients must retain the database generic.
  browser.from("missing_table");
  // @ts-expect-error Server clients must retain the database generic.
  server.from("missing_table");
  // @ts-expect-error Request status must be one of the database enum values.
  client.from("procurement_requests").update({ status: "invalid_status" });
  // @ts-expect-error Calculated totals are generated by PostgreSQL, never written by clients.
  client.from("request_items").update({ total_amount: 123 });
  // @ts-expect-error Required RPC parameters must be supplied.
  client.rpc("save_payment_request_revision", { target_payment_id: "synthetic" });
  // @ts-expect-error Misspelled RPCs must fail at compile time.
  client.rpc("missing_function");
  const query = client
    .from("procurement_requests")
    .select("id, profiles!procurement_requests_requester_id_fkey(full_name)");
  type Row = QueryData<typeof query>[number];
  const valid: Row = { id: "synthetic", profiles: { full_name: "ทดสอบ" } };
  // @ts-expect-error The many-to-one relation is an object, not an array.
  const invalid: Row = { id: "synthetic", profiles: [{ full_name: "ทดสอบ" }] };
  const nullableSize: Tables<"request_attachments">["size_bytes"] = null;
  return { query, valid, invalid, nullableSize };
}
